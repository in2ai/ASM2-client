import os
import subprocess
from pathlib import Path
import pandas as pd
import re

BASE_DIR = "benchmark/dataset_generation/narrativeqa"

START_PATTERN = re.compile(r"(?m)^\*\*\*\s*START.*(?:\r?\n|$)")
END_PATTERN = re.compile(r"(?m)^\*\*\*\s*END.*$")


def refine_documents(input_csv, output_csv):
    """
    Refines the documents CSV by filtering for 'gutenberg' kind and saves the result to a new CSV file.

    Args:
        input_csv (str): Path to the input CSV file containing documents.
        output_csv (str): Path to the output CSV file to save refined documents.

    Returns:
        int: The number of rows in the refined DataFrame.
    """

    print("\nRefining documents...")
    df = pd.read_csv(input_csv)
    df_refined = df[df["kind"] == "gutenberg"].copy()
    df_refined.to_csv(output_csv, index=False)
    num_rows = len(df_refined)
    print(f"Refined documents saved to {output_csv} with {num_rows} rows.")

    return num_rows


def download_stories(csv_file, num_rows, script_path=f"{BASE_DIR}/download_stories.sh"):
    """
    Runs the download_stories.sh script, which downloads the stories referenced
    in the given CSV file into the corpus/ directory.

    Args:
        csv_file (str): Name of the CSV file (relative to the script directory).
        num_rows (int): Number of rows to use with tail -n.
        script_path (str): Path to the download_stories.sh script.

    Returns:
        subprocess.CompletedProcess: The result of the executed script.
    """
    if not os.path.isfile(script_path):
        raise FileNotFoundError(f"Script not found: {script_path}")

    return subprocess.run(
        ["bash", script_path, csv_file, str(num_rows)], check=True
    )


def find_size_mismatches(corpus_dir, id_url_csv, min_diff_percent=30):
    """
    Compares the size of each downloaded file against the expected size stored
    in the id_url CSV and returns the ones that differ by at least
    min_diff_percent (missing files are always considered mismatches).

    Must be checked right after download_stories() and before trim_story/
    process_txts, since trimming and deleting change the file sizes.

    Args:
        corpus_dir (str): Directory containing the downloaded <id>.txt files.
        id_url_csv (str): CSV with columns id,kind,url,fs (generated by
            download_stories.sh as <csv_stem>_id_url.csv).
        min_diff_percent (float): Minimum size difference (%) to flag a file.

    Returns:
        list[dict]: One dict per mismatching file with keys
            id, actual_size, expected_size and diff_percent.
    """
    corpus_path = Path(corpus_dir)

    df = pd.read_csv(id_url_csv, header=None, names=["id", "kind", "url", "fs"])

    mismatches = []
    for row in df.itertuples(index=False):
        expected_size = pd.to_numeric(row.fs, errors="coerce")
        if pd.isna(expected_size) or expected_size <= 0:
            continue

        file = corpus_path / f"{row.id}.txt"
        actual_size = file.stat().st_size if file.is_file() else 0

        diff_percent = abs(actual_size - expected_size) / expected_size * 100
        if diff_percent >= min_diff_percent:
            mismatches.append(
                {
                    "id": row.id,
                    "actual_size": actual_size,
                    "expected_size": int(expected_size),
                    "diff_percent": diff_percent,
                }
            )

    return mismatches


def download_stories_verified(
    csv_file,
    num_rows,
    corpus_dir,
    id_url_csv,
    min_diff_percent=30,
    max_retries=5,
):
    """
    Downloads the stories and retries any file whose size differs from the
    expected one by at least min_diff_percent. Mismatching files are deleted so
    that re-running download_stories.sh (which uses wget -nc) re-fetches only
    those, continuing where it left off instead of starting from scratch.

    Args:
        csv_file (str): Name of the CSV file passed to download_stories.
        num_rows (int): Number of rows to download.
        corpus_dir (str): Directory containing the downloaded <id>.txt files.
        id_url_csv (str): CSV with columns id,kind,url,fs.
        min_diff_percent (float): Minimum size difference (%) to retry a file.
        max_retries (int): Maximum number of retry rounds.

    Returns:
        list[dict]: Files that still mismatch after all retries (empty if OK).
    """

    print("\nDownloading stories (with size verification and retries)...")

    download_stories(csv_file, num_rows)

    corpus_path = Path(corpus_dir)
    mismatches = find_size_mismatches(corpus_dir, id_url_csv, min_diff_percent)

    for attempt in range(1, max_retries + 1):
        if not mismatches:
            break

        print(
            f"  Retry {attempt}/{max_retries}: "
            f"{len(mismatches)} file(s) with >= {min_diff_percent}% size difference."
        )

        # Delete the mismatching files so wget -nc re-fetches only those.
        for mismatch in mismatches:
            file = corpus_path / f"{mismatch['id']}.txt"
            file.unlink(missing_ok=True)

        download_stories(csv_file, num_rows)
        mismatches = find_size_mismatches(corpus_dir, id_url_csv, min_diff_percent)

    if mismatches:
        print(
            f"  WARNING: {len(mismatches)} file(s) still differ by "
            f">= {min_diff_percent}% after {max_retries} retries:"
        )
        for mismatch in mismatches:
            print(
                f"   - {mismatch['id']}: {mismatch['actual_size']} bytes "
                f"vs expected {mismatch['expected_size']} bytes "
                f"({mismatch['diff_percent']:.1f}% diff)"
            )

    print("Stories downloaded successfully.")

    return mismatches


def trim_story(text: str) -> str | None:
    """
    Trims a Project Gutenberg story, keeping only the text between the START and
    END markers and discarding the surrounding legal header/footer.

    Args:
        text (str): Full raw text of the story.

    Returns:
        str | None: The trimmed story text, or None if no START marker is found.
            If a START marker is present but no END marker, everything after
            START is returned.
    """
    start = START_PATTERN.search(text)
    if not start:
        return None

    rest = text[start.end():]
    end = END_PATTERN.search(rest)

    if end:
        return rest[:end.start()].strip()

    return rest.strip()


def process_txts(input_dir: str):
    """
    Trims every .txt file under input_dir in place using trim_story, overwriting
    the original files with their trimmed content. Files without a START marker
    or with empty content after trimming are left untouched and reported in a
    summary printed at the end.

    Args:
        input_dir (str): Directory containing the .txt files to process.

    Raises:
        FileNotFoundError: If input_dir does not exist.
    """
    print("\nProcessing .txt files...")

    input_path = Path(input_dir)

    if not input_path.exists():
        raise FileNotFoundError(f"Input folder does not exist: {input_path}")

    processed = 0
    without_start = []
    empty = []
    errors = []

    for file in input_path.rglob("*.txt"):
        try:
            with file.open("r", encoding="utf-8", errors="replace") as f:
                content = f.read()

            trimmed = trim_story(content)

            if trimmed is None:
                without_start.append(str(file))
                continue

            if not trimmed:
                empty.append(str(file))
                continue

            file.write_text(trimmed, encoding="utf-8")
            processed += 1

        except Exception as e:
            errors.append((str(file), str(e)))

    print("=== SUMMARY ===")
    print(f"Files processed and saved: {processed}")
    print(f"Files without start marker: {len(without_start)}")
    print(f"Files with empty trim: {len(empty)}")
    print(f"Errors: {len(errors)}")

    if without_start:
        print("\nFiles without start marker:")
        for file in without_start:
            print(f" - {file}")

    if empty:
        print("\nFiles with empty trim:")
        for file in empty:
            print(f" - {file}")

    if errors:
        print("\nErrors:")
        for file, error in errors:
            print(f" - {file}: {error}")
    
    print("Processing of .txt files completed.")


def delete_small_txt_files(source_folder, minimum_size_kb=100):
    """
    Deletes .txt files in source_folder that are smaller than minimum_size_kb,
    keeping only documents large enough to yield a meaningful number of chunks.

    Args:
        source_folder (str): Directory containing the .txt files.
        minimum_size_kb (int): Minimum file size (in KB) to keep a file.

    Returns:
        int: Number of files deleted.
    """
    print("\nDeleting small .txt files...")
    source = Path(source_folder)

    minimum_size = minimum_size_kb * 1024

    deleted = 0
    for file in source.glob("*.txt"):
        if file.is_file() and file.stat().st_size < minimum_size:
            file.unlink()
            deleted += 1

    print(f"Deleted .txt files smaller than {minimum_size_kb} KB.")

    return deleted


def delete_auxiliary_files(file_paths):
    """
    Deletes intermediate/auxiliary files produced by the pipeline (e.g.
    refined_documents.csv, refined_documents_id_url.csv). Missing files are
    skipped silently.

    Args:
        file_paths (Iterable[str]): Paths of the files to delete.

    Returns:
        int: Number of files actually deleted.
    """
    print("\nDeleting auxiliary files...")

    deleted = 0
    for file_path in file_paths:
        file = Path(file_path)
        if file.is_file():
            file.unlink()
            deleted += 1
            print(f" - Deleted {file}")

    print(f"Deleted {deleted} auxiliary file(s).")

    return deleted


def add_book_title_to_questions(qa_df, documents_csv_path):
    """
    Prefixes each question with the book title looked up from the documents CSV,
    e.g. "Regarding the book '<title>': <question>". Titles are matched on
    document_id; missing titles fall back to "Unknown Title".

    Args:
        qa_df (pd.DataFrame): QA DataFrame with at least document_id and
            question columns.
        documents_csv_path (str): Path to the documents CSV containing
            document_id and wiki_title columns.

    Returns:
        pd.DataFrame: The QA DataFrame with the question column updated.
    """
    documents_df = pd.read_csv(documents_csv_path)
    documents_df = documents_df[["document_id", "wiki_title"]].copy()

    merged_df = qa_df.merge(documents_df, on="document_id", how="left")

    merged_df["question"] = (
        "Regarding the book '"
        + merged_df["wiki_title"].fillna("Unknown Title")
        + "': "
        + merged_df["question"].astype(str)
    )

    merged_df.drop(columns=["wiki_title"], inplace=True)

    return merged_df


def generate_qa_dataset(
    data_dir,
    csv_path,
    output_path,
    documents_csv_path,
    max_questions_per_document,
    max_documents=None,
    random_state=None,
):
    """
    Builds the QA dataset from the QAPs CSV, keeping only questions whose
    document_id matches a .txt file in data_dir. For each document up to
    max_questions_per_document questions are sampled, whitespace is stripped
    from text columns, an evaluation_id is added, the book title is prefixed to
    each question, and the result is saved to output_path.

    Args:
        data_dir (str): Directory with the corpus .txt files (their stems are
            the document_ids to keep).
        csv_path (str): Path to the input QAPs CSV.
        output_path (str): Path to the output CSV to create.
        documents_csv_path (str): Path to the documents CSV, used to prefix the
            book title to each question.
        max_questions_per_document (int): Maximum questions sampled per document.
        max_documents (int | None): Maximum number of documents to include
            (None for no limit).
        random_state (int | None): Seed for reproducible question sampling.

    Returns:
        pd.DataFrame: The generated QA DataFrame (with book titles added).
    """

    print("\nGenerating QA dataset...")
    data_dir = Path(data_dir)
    csv_path = Path(csv_path)
    output_path = Path(output_path)

    selected_columns = ["document_id", "question", "answer1"]

    document_paths = sorted(data_dir.rglob("*.txt"), key=lambda path: path.stem)

    if max_documents is not None:
        document_paths = document_paths[:max_documents]

    document_ids = [file.stem for file in document_paths]

    df = pd.read_csv(csv_path)
    filtered_df = df.loc[df["document_id"].isin(document_ids), selected_columns].copy()

    # Remove leading/trailing whitespace coming from the original NarrativeQA data.
    text_columns = filtered_df.select_dtypes(include="object").columns
    filtered_df[text_columns] = filtered_df[text_columns].apply(lambda col: col.str.strip())

    sampled_groups = []
    for _, group in filtered_df.groupby("document_id", sort=False):
        sampled_group = group.sample(
            n=min(len(group), max_questions_per_document),
            random_state=random_state,
        )
        sampled_groups.append(sampled_group)

    if sampled_groups:
        limited_df = pd.concat(sampled_groups, ignore_index=True)
    else:
        limited_df = pd.DataFrame(columns=selected_columns)

    limited_df.insert(0, "evaluation_id", range(1, len(limited_df) + 1))

    limited_df = add_book_title_to_questions(limited_df, documents_csv_path)

    # Tag the data source of the dataset
    limited_df.insert(1, "source", "narrativeqa")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    limited_df.to_csv(output_path, index=False)

    print(f"QA dataset generated and saved to {output_path}.")

    return limited_df


def main():
    print("Starting NarrativeQA dataset generation...")

    # refining the documents CSV to include only 'gutenberg' kind
    documents_csv_path = f"{BASE_DIR}/asm2-narrativeqa-documents.csv"  # Path to the input CSV file
    refined_documents_csv_path = f"{BASE_DIR}/refined_documents.csv"  # Path to save the refined documents
    num_rows = refine_documents(documents_csv_path, refined_documents_csv_path)

    # Download stories with size verification and retries
    refined_documents_filename = Path(refined_documents_csv_path).name
    corpus_dir = f"{BASE_DIR}/corpus"
    id_url_csv = f"{BASE_DIR}/{Path(refined_documents_filename).stem}_id_url.csv"
    download_stories_verified(
        csv_file=refined_documents_filename,
        num_rows=num_rows,
        corpus_dir=corpus_dir,
        id_url_csv=id_url_csv,
        min_diff_percent=30,
        max_retries=5,
    )
    
    # Process the downloaded .txt files to trim them based on START and END markers
    process_txts(corpus_dir)

    # Delete small .txt files (less than 100 KB) to assure documents with a large number of chunks
    minimum_size_kb = 100
    delete_small_txt_files(source_folder=corpus_dir, minimum_size_kb=minimum_size_kb)
    
    # Generate the QA dataset with a maximum number of questions per document and a maximum number of documents
    max_questions = 5 # Maximum number of questions per document
    max_docs = 200 # Maximum number of documents to include in the final dataset
    qaps_csv_path = f"{BASE_DIR}/asm2-narrativeqa-qaps.csv"  # Path to the input CSV file for QAPs
    refined_qaps_csv_path = f"{BASE_DIR}/dataset_narrativeqa_qa_{max_questions}_docs_{max_docs}.csv"  # Path to save the refined QAPs
    _ = generate_qa_dataset(
        data_dir=corpus_dir,
        csv_path=qaps_csv_path,
        output_path=refined_qaps_csv_path,
        documents_csv_path=documents_csv_path,
        max_questions_per_document=max_questions,
        max_documents=max_docs,
        random_state=42,
    )

    # Clean up intermediate files that are no longer needed
    delete_auxiliary_files([refined_documents_csv_path, id_url_csv])

    print("\nDataset generation completed.")


if __name__ == "__main__":
    main()